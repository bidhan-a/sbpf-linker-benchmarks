//! Generates the program registration from `programs/manifest.json`.

use std::{env, fs, path::Path};

fn main() {
    let manifest_dir = env::var("CARGO_MANIFEST_DIR").expect("CARGO_MANIFEST_DIR is set by cargo");
    let manifest_path = Path::new(&manifest_dir).join("programs/manifest.json");
    println!("cargo:rerun-if-changed={}", manifest_path.display());

    let manifest: serde_json::Value =
        serde_json::from_slice(&fs::read(&manifest_path).expect("failed to read manifest"))
            .expect("failed to parse `programs/manifest.json`");
    let programs = manifest
        .get("programs")
        .and_then(serde_json::Value::as_array)
        .expect("`programs/manifest.json` must contain a `programs` array");

    let mut generated = String::from(
        "// @generated by build.rs from `programs/manifest.json`; do not edit.\n\n\
         fn registrations() -> Vec<harness::ProgramRegistration> {\n    vec![\n",
    );
    for program in programs {
        let name = program
            .get("name")
            .and_then(serde_json::Value::as_str)
            .unwrap_or_else(|| panic!("manifest program name must be a string: {program}"));
        let crate_name = name.replace('-', "_");
        assert!(
            is_valid_ident(&crate_name),
            "manifest program name `{name}` does not map to a valid Rust crate name"
        );

        let has_benchmarks = program
            .get("benchmarks")
            .and_then(serde_json::Value::as_array)
            .is_some_and(|benchmarks| !benchmarks.is_empty());
        if has_benchmarks {
            generated.push_str(&format!(
                "    harness::ProgramRegistration::new(\"{name}\", {crate_name}::benchmark::run),\n"
            ));
        }
    }
    generated.push_str("    ]\n}\n");

    let out_dir = env::var("OUT_DIR").expect("OUT_DIR is set by cargo");
    fs::write(Path::new(&out_dir).join("programs.rs"), generated)
        .expect("failed to write generated programs.rs");
}

fn is_valid_ident(name: &str) -> bool {
    let mut chars = name.chars();
    matches!(chars.next(), Some(first) if first.is_ascii_alphabetic() || first == '_')
        && name.chars().all(|c| c.is_ascii_alphanumeric() || c == '_')
}
